/** How far outside an outline a place still counts as inside (degrees, about the simplification: a coast, a border). */
const OUTLINE_MARGIN_DEG = 0.015

/** True when `at` lies inside one of the rings (even-odd rule), or within OUTLINE_MARGIN_DEG of one. */
export function insideOutline({ lon, lat }: LonLat, outline: Outline): boolean {
  const m = OUTLINE_MARGIN_DEG
  const around: [number, number][] = [[0, 0], [m, 0], [-m, 0], [0, m], [0, -m]]
  return around.some(([dx, dy]) => insideRings(lon + dx, lat + dy, outline))
}

function insideRings(lon: number, lat: number, outline: Outline): boolean {
  return outline.some((ring) => {
    let inside = false
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[i]
      const [x2, y2] = ring[j]
      if (y1 > lat !== y2 > lat && lon < ((x2 - x1) * (lat - y1)) / (y2 - y1) + x1) inside = !inside
    }
    return inside
  })
}
